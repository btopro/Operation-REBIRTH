"""Locate native blue eyes and their sclera/pupil pixels, retaining skin and hair."""
from pathlib import Path
from PIL import Image
import json
r=Path(__file__).resolve().parents[2];out={}
for kind in ['idle','walk','run','jump','fall','moves']:
 im=Image.open(r/f'public/assets/fighters/young-link/{kind}_sheet.png').convert('RGBA');frames=[]
 for top in range(0,im.height,128):
  for left in range(0,im.width,160):
   cel=im.crop((left,top,left+160,top+128));seeds=[(x,y) for y in range(128) for x in range(160) if cel.getpixel((x,y))==(21,101,189,255)];mask=set()
   for x,y in seeds:
    whites={(xx,yy) for yy in range(max(0,y-2),min(128,y+3)) for xx in range(max(0,x-2),min(160,x+3)) if cel.getpixel((xx,yy))==(249,249,249,255)}
    connected={(x,y)}
    while True:
     adjacent={p for p in whites if any(max(abs(p[0]-q[0]),abs(p[1]-q[1]))<=1 for q in connected)}
     if adjacent<=connected:break
     connected|=adjacent
    mask|=connected
    xs=[p[0] for p in connected];lo,hi=min(xs),max(xs)
    if lo==hi:hi=min(159,hi+1)
    for yy in range(max(0,y-2),y+1):
     for xx in range(lo,hi+1):
      if cel.getpixel((xx,yy))==(8,8,8,255):mask.add((xx,yy))
   frames.append(sorted(mask))
 out['yl_'+kind]=frames
(r/'src/fighters/youngLinkEyes.js').write_text('// Generated by tools/sprites/young_link_eyes.py: local eye pixels for every native cel.\nexport const YOUNG_LINK_EYES='+json.dumps(out,separators=(',',':'))+';\n')
print('Eye masks:',sum(bool(f) for fs in out.values() for f in fs),'open-eye cels')
