"""Losslessly trim move cels; retain every frame number, logical size and origin."""
from pathlib import Path
from PIL import Image
import json,hashlib,math,subprocess
ROOT=Path(__file__).resolve().parents[2]
loads=json.loads(subprocess.check_output(['node',str(ROOT/'tools/sprites/sprite_loads.mjs')],cwd=ROOT))
manifest={};before=after=0
for a in loads:
 key,path,c=a['key'],a['path'],a['config']
 if not path.startswith('assets/fighters/') or 'idle' in key or key in {'hk_attack1','hk_attack2','hk_counter','hk_death','hk_fall','hk_grab','hk_guard','hk_hit','hk_jump','hk_moves','hk_run','hk_shrine','hk_shrine_turn','hk_shrine_weapon'}:continue
 im=Image.open(ROOT/'public'/path).convert('RGBA')
 if im.width*im.height*4<1048576:continue
 fw,fh=c['frameWidth'],c['frameHeight'];cols=im.width//fw
 cells=[];seen={};frames={};unique=[]
 for i in range(cols*(im.height//fh)):
  cel=im.crop((i%cols*fw,i//cols*fh,i%cols*fw+fw,i//cols*fh+fh));b=cel.getbbox() or (0,0,1,1)
  # Two transparent pixels allow outlines without adjacent-frame contamination.
  b=(max(0,b[0]-2),max(0,b[1]-2),min(fw,b[2]+2),min(fh,b[3]+2));trim=cel.crop(b)
  signature=(trim.size,hashlib.sha256(trim.tobytes()).digest())
  if signature not in seen:seen[signature]=len(unique);unique.append(trim)
  cells.append((seen[signature],b))
 width=2048;x=y=row=0;positions=[]
 for cel in unique:
  w,h=cel.size
  if x+w>width:x=0;y+=row;row=0
  positions.append((x,y));x+=w;row=max(row,h)
 height=y+row;atlas=Image.new('RGBA',(width,height))
 for cel,(x,y) in zip(unique,positions):atlas.paste(cel,(x,y))
 for i,(index,b) in enumerate(cells):
  x,y=positions[index];w,h=unique[index].size
  frames[str(i)]={'frame':{'x':x,'y':y,'w':w,'h':h},'rotated':False,'trimmed':True,'spriteSourceSize':{'x':b[0],'y':b[1],'w':w,'h':h},'sourceSize':{'w':fw,'h':fh}}
 stem='assets/mobile/'+key;atlas.save(ROOT/'public'/(stem+'.png'),optimize=False)
 data={'frames':frames,'meta':{'app':'REBIRTH lossless mobile packer','original':{'width':im.width,'height':im.height,'frameWidth':fw,'frameHeight':fh,'columns':cols}}}
 (ROOT/'public'/(stem+'.json')).write_text(json.dumps(data,separators=(',',':')))
 manifest[key]={'image':stem+'.png','json':stem+'.json','original':data['meta']['original']}
 before+=im.width*im.height*4;after+=width*height*4
(ROOT/'src/mobileAtlasManifest.js').write_text('// Generated by tools/sprites/mobile_atlases.py\nexport const MOBILE_ATLASES='+json.dumps(manifest,separators=(',',':'))+';\n')
(ROOT/'public/assets/mobile/report.json').write_text(json.dumps({'sheets':len(manifest),'originalBytes':before,'packedBytes':after,'savedPercent':round((1-after/before)*100,1)}))
print(len(manifest),'sheets',round(before/1048576),'MiB ->',round(after/1048576),'MiB')
