"""Losslessly extract the user-supplied Mii Brawler JUS sheet (TheSpriteAnimations).
Run: python3 tools/sprites/fists.py /path/to/original.png
Only the flat background is keyed out. Native artwork uses nearest-neighbor 1.5x scaling to match the cast.
"""
from pathlib import Path
from PIL import Image
import sys,json,statistics
ROOT=Path(__file__).resolve().parents[2]
REGIONS={'idle':(0,105,108,145),'run':(368,163,826,206),'walk':(250,163,342,206),'jump':(0,244,270,290),'guard':(0,313,145,355),'taunt':(0,377,108,419),'jab':(0,437,112,475),'sideB':(0,495,493,536),'upb':(0,558,262,616),'downB':(0,641,300,677),'airB':(0,698,281,754),'ftilt':(0,780,185,817),'fsmash':(0,841,202,881),'utilt':(0,904,363,953),'dtilt':(0,987,278,1028),'nair':(0,1046,213,1092),'rapid':(0,1169,427,1213),'rush':(0,1217,796,1263),'upflame':(0,1383,417,1443),'downsmash':(0,1555,762,1614),'dive':(0,1685,828,1744),'hurt':(0,1946,341,1994),'win':(0,2022,639,2067),'lose':(0,2096,37,2131)}
SCALE=1.5
BG=(186,68,64)
SHIRT={(201,42,68),(230,76,77)}
im=Image.open(sys.argv[1]).convert('RGBA');px=im.load()
for y in range(im.height):
 for x in range(im.width):
  if px[x,y][:3]==BG:px[x,y]=(0,0,0,0)
clips={};rects={}
for name,(x1,y1,x2,y2) in REGIONS.items():
 a=im.crop((x1,y1,x2,y2));bands=[];start=None
 for x in range(a.width+1):
  on=x<a.width and any(a.getpixel((x,y))[3] for y in range(a.height))
  if on and start is None:start=x
  if not on and start is not None:bands.append([start,x]);start=None
 # Split two touching neighboring sprites; attach detached effect pixels to their own frame.
 if name=='sideB':bands=[[3,34],[34,66]]+bands[1:]
 if name=='nair':bands=[[3,33],[33,74]]+bands[1:]
 for i in range(len(bands)-1,-1,-1):
  lo,hi=bands[i]
  if hi-lo>=10:continue
  prev=lo-bands[i-1][1] if i else 999;after=bands[i+1][0]-hi if i+1<len(bands) else 999
  if prev<after:bands[i-1][1]=hi;bands.pop(i)
  else:bands[i+1][0]=lo;bands.pop(i)
 crops=[a.crop((lo,0,hi,a.height)) for lo,hi in bands]
 baseline=crops[0].getbbox()[3]
 frames=[]
 for raw in crops:
  torso=[x for y in range(raw.height) for x in range(raw.width) if raw.getpixel((x,y))[:3] in SHIRT and raw.getpixel((x,y))[3]]
  hair=[x for y in range(raw.height) for x in range(raw.width) if raw.getpixel((x,y))[:3] in {(18,28,17),(29,45,27),(46,73,45)} and raw.getpixel((x,y))[3]]
  anchor=round(statistics.median(torso or hair)) if (torso or hair) else raw.width//2
  frames.append((raw,anchor,baseline))
 clips[name]=frames;rects[name]=[[x1+lo,y1,x1+hi,y2] for lo,hi in bands]
out=ROOT/'public/assets/fighters/fists';out.mkdir(parents=True,exist_ok=True)
def pack(frames,w,h,foot,cols):
 image=Image.new('RGBA',(w*cols,h*((len(frames)+cols-1)//cols)))
 for i,(raw,anchor,baseline) in enumerate(frames):
  sprite=raw.resize((round(raw.width*SCALE),round(raw.height*SCALE)),Image.Resampling.NEAREST);dx=w//2-round(anchor*SCALE);dy=foot-round(baseline*SCALE)
  bbox=sprite.getbbox()
  if dx+bbox[0]<0 or dx+bbox[2]>w or dy+bbox[1]<0 or dy+bbox[3]>h:raise ValueError(('clipped frame',i,raw.size,bbox,dx,dy))
  image.alpha_composite(sprite,(i%cols*w+dx,i//cols*h+dy))
 return image
for name in ['idle','run','walk','jump']:
 pack(clips[name],96,96,88,len(clips[name])).save(out/(name+'_sheet.png'))
fall=[clips['jump'][i] for i in [5,6,7,8]];pack(fall,96,96,88,4).save(out/'fall_sheet.png')
pool=[];indices={}
for name,frames in clips.items():
 if name in ['idle','run','walk','jump']:continue
 indices[name]=list(range(len(pool),len(pool)+len(frames)));pool.extend(frames)
pack(pool,192,192,136,16).save(out/'moves_sheet.png')
manifest={'frameWidth':192,'frameHeight':192,'frameCount':len(pool),'clips':indices,'rects':rects,'counts':{k:len(v) for k,v in clips.items()}}
(out/'manifest.json').write_text(json.dumps(manifest,indent=2))
(ROOT/'src/fighters/fistsAnims.js').write_text('// Extracted from the supplied sheet by TheSpriteAnimations. Generated by tools/sprites/fists.py.\nexport const FISTS_CLIPS='+json.dumps(indices,separators=(',',':'))+';\n')
print('Extracted',sum(len(v) for v in clips.values()),'native frames;',len(pool),'move frames; native colors preserved at 1.5x.')
