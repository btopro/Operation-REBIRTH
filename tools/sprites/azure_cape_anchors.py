"""Export per-cel shoulder anchors, using the exact transforms that build Lacy's moves."""
import sys,json,math
from pathlib import Path
import numpy as np
from PIL import Image
sys.path.insert(0,str(Path(__file__).parent))
import hero_knight_moves as H
import colorsys
def anchor(frame):
 a=np.array(frame);rgb=a[...,:3]/255;mx=rgb.max(2);mn=rgb.min(2)
 # Original red scarf is the only saturated red material in the base knight strips.
 mask=(a[...,3]==255)&(rgb[...,0]>rgb[...,1]*1.3)&(rgb[...,0]>rgb[...,2]*1.2)&(mx-mn>.18)
 ys,xs=np.nonzero(mask)
 if len(xs)<4:return None
 top=int(ys.min());return (float(xs[ys<=top+3].mean()),top)
ANCHOR_FALLBACK={('attack2',0):(69,51)}
root=Path(__file__).resolve().parents[2];folder=root/'public/assets/fighters/hero-knight'
def shoulder(img,name,i):
 a=anchor(Image.fromarray(img)) or ANCHOR_FALLBACK.get((name,i)) or (66,51)
 return (round(a[0]-3,2),a[1]+2)
out={}
for p in folder.glob('*_sheet.png'):
 name=p.name[:-10]
 if name=='moves':continue
 im=np.array(Image.open(p).convert('RGBA'))
 if im.shape[0]!=90 or im.shape[1]%150:continue
 out['hk_'+name]=[list(shoulder(im[:,i*150:(i+1)*150],name,i))+[0,False] for i in range(im.shape[1]//150)]
C=H.Costume('');anchors=[]
for name,(ticks,keys,center,fx) in H.MOVES.items():
 for t in range(0,ticks,H.STEP):
  cur=max(i for i,k in enumerate(keys) if k[0]<=t);nxt=min(cur+1,len(keys)-1)
  t0,cel,xf0,_=keys[cur];t1,_,xf1,e=keys[nxt]
  k=0 if nxt==cur else H.EASE[e]((t-t0)/max(1,t1-t0));xf=H.lerp(xf0,xf1,k)
  strip,f,flip=cel;x,y=shoulder(C.frame(strip,f),strip,f)
  if flip:x=132-x
  rig=C.rig(strip,f,flip,center);point=rig.matrix('b',{'root':xf})@np.array([x,y,1])
  anchors.append([round(float(point[0]),2),round(float(point[1]),2),round(math.radians(xf[0]),5),flip])
out['hk_moves']=anchors
(root/'src/fighters/azureCapeAnchors.js').write_text('// Generated by tools/sprites/azure_cape_anchors.py\nexport const AZURE_CAPE_ANCHORS='+json.dumps(out,separators=(',',':'))+';\n')
print('Anchors:',sum(map(len,out.values())), 'cels')
