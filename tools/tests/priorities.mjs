// Browser integration checks for challenges, feedback and rematches. Runs offline.
import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import { readFileSync, mkdirSync } from 'node:fs';
const server = await createServer({ server: { host: '127.0.0.1', port: 0 }, logLevel: 'silent' });
await server.listen();
const url = server.resolvedUrls.local[0];
const browser = await chromium.launch({ executablePath: process.env.SIM_CHROME || '/usr/bin/chromium', headless: true, args: ['--mute-audio', '--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  await page.route('**/*', (r) => {
    const u = r.request().url();
    if (u.includes('/npm/phaser@')) return r.fulfill({ body: readFileSync('node_modules/phaser/dist/phaser.min.js'), contentType: 'application/javascript' });
    return u.startsWith(url) ? r.continue() : r.abort();
  });
  await page.goto(url);
  await page.waitForFunction(() => window.game?.scene.isActive('Title'), null, { timeout: 60000 });
  const result = await page.evaluate(async () => {
    const { CHALLENGES, recordChallenge, challengeProgress } = await import('/src/challenges.js');
    const { getCoins } = await import('/src/progress.js');
    const { settings } = await import('/src/settings.js');
    const checks = [];
    const check = (ok, name) => { if (!ok) throw new Error(name); checks.push(name); };
    const challenge = CHALLENGES[0], before = getCoins();
    recordChallenge('soul-summoner', 'summon', { cpu: true });
    recordChallenge('soul-summoner', 'summon', { demo: true });
    check(challengeProgress(challenge) === 0, 'CPUs and demos cannot earn challenges');
    recordChallenge('mr-wake', 'summon');
    check(challengeProgress(challenge) === 0, 'Challenges require the matching fighter');
    for (let i = 0; i < 7; i++) recordChallenge('soul-summoner', 'summon');
    check(challengeProgress(challenge) === 3 && getCoins() === before + 30, 'Challenge progress caps and rewards exactly once');
    const game = window.game;
    const go = async (key, data) => {
      for (const s of game.scene.getScenes(true)) game.scene.stop(s.scene.key);
      game.scene.start(key, data);
      await new Promise((r) => setTimeout(r, 150));
      return game.scene.getScene(key);
    };
    const screen = await go('Challenges');
    check(screen.cards.length === 3 && screen.cards[0].text.startsWith('DONE'), 'Challenge menu displays saved progress');
    screen.pick(1); check(screen.nameT.text === 'MR WAKE', 'Challenge fighter navigation');
    screen.practise(); await new Promise((r) => setTimeout(r, 200));
    let match = game.scene.getScene('Match');
    check(match.isTraining && match.fighters[0].def.id === 'mr-wake' && !match.fighters[0].isCpu, 'Practice starts selected human fighter');
    check(match.fighters.length === 2 && match.fighters[1].isCpu, 'Practice includes a dummy');
    match.countdown = 0;
    const f = match.fighters[0];
    match.combatCue(f, 'dodge'); const pops = match.pops.length;
    match.combatCue(f, 'dodge');
    check(match.pops.length === pops, 'Dodge feedback does not spam');
    match.combatCue(f, 'ready'); f.breakShield();
    check(match.pops.some((p) => p.t.text === 'SHIELD BREAK!') && match.pops.some((p) => p.t.text === 'LIMIT READY!'), 'Shield and Limit feedback render');
    const completedBefore = challengeProgress(CHALLENGES[3]);
    match.spawnPool(f, f.def.moves.downB.pool);
    check(challengeProgress(CHALLENGES[3]) === completedBefore + 1, 'Successful Shadow Pool advances character lesson');
    Object.assign(settings, { mode: 'stock', from: 'Setup', stocks: 2, cpuCount: 1, extraPads: [], p1Pad: null, picks: ['random', 'mr-wake'], skins: [0, 0], stage: 'random', hazards: false, items: false });
    match = await go('Match'); match.countdown = 0;
    const wanted = { fighters: match.fighters.map((f) => f.def.id), stage: match.stageId };
    match.toResults(); await new Promise((r) => setTimeout(r, 150));
    if (game.scene.isActive('Win')) game.scene.getScene('Win').done();
    await new Promise((r) => setTimeout(r, 150));
    const results = game.scene.getScene('Results');
    check(game.scene.isActive('Results') && results.rematch.stage === wanted.stage, 'Resolved random stage reaches results');
    check(JSON.stringify(results.rematch.picks) === JSON.stringify(wanted.fighters), 'Resolved random fighters retained');
    results.t = 0; results.choose(0); check(!results.leaving, 'Held confirm cannot immediately start rematch');
    results.t = 41; results.choose(0); results.choose(0);
    await new Promise((r) => setTimeout(r, 200));
    match = game.scene.getScene('Match');
    check(game.scene.isActive('Match') && match.stageId === wanted.stage && JSON.stringify(match.fighters.map((f) => f.def.id)) === JSON.stringify(wanted.fighters), 'Quick rematch preserves actual stage and fighters');
    check(match.fighters.every((f) => f.percent === 0 && f.stocks === 2) && !match.stage.hazardsOn, 'Rematch resets battle state and retains rules');
    return checks;
  });
  console.log(result.map((x) => 'PASS ' + x).join('\n'));
  await page.reload();
  await page.waitForFunction(() => window.game?.scene.isActive('Title'), null, { timeout: 60000 });
  assert.equal(await page.evaluate(async () => { const c = await import('/src/challenges.js'); return c.challengeProgress(c.CHALLENGES[0]); }), 3);
  console.log('PASS Challenge completion persists after reload');
  await page.evaluate(() => { const g = window.game; for (const s of g.scene.getScenes(true)) g.scene.stop(s.scene.key); g.scene.start('Challenges'); });
  await page.waitForTimeout(400);
  mkdirSync('recordings/test-output/rebirth-priorities', { recursive: true });
  await page.screenshot({ path: 'recordings/test-output/rebirth-priorities/challenges.png' });
  assert.deepEqual(errors, []);
  console.log('PASS No browser runtime errors');
} finally { await browser.close(); await server.close(); }
